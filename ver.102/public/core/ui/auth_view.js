/**
 * JX - IDLE: Martial Arts Landing & Authentication Enhancer (auth.js)
 * Clean, focused Wuxia authentication card with pattern-wind accent,
 * precise top-left and bottom-right corner brackets, and antique brass double-bordered buttons.
 */
(function () {
  function cleanLegacyStyles() {
    const legacy = document.getElementById("ngateCss");
    if (legacy) {
      legacy.remove();
    }
  }

  function enhanceAuthModal() {
    cleanLegacyStyles();

    const ng2 = document.querySelector(".ng2");
    if (!ng2 || ng2.dataset.enhanced === "true") return;

    const uInput = document.getElementById("ngU");
    const pInput = document.getElementById("ngP");
    const showCb = document.getElementById("ngShow");
    const showLbl = ng2.querySelector('.cl[data-cb="ngShow"]');
    const remCb = document.getElementById("ngRem");
    const remLbl = ng2.querySelector('.cl[data-cb="ngRem"]');
    const btnIn = document.getElementById("ngIn");
    const btnUp = document.getElementById("ngUp");
    const ng2x = document.querySelector(".ng2x");

    if (!uInput || !pInput || !btnIn || !btnUp) return;

    ng2.dataset.enhanced = "true";

    // Clean inline styles generated by legacy engine
    [uInput, pInput, showCb, showLbl, remCb, remLbl, btnIn, btnUp].forEach((el) => {
      if (el) el.removeAttribute("style");
    });

    // 1. Wind & Cloud Pattern Decorative Background
    const windPattern = document.createElement("img");
    windPattern.className = "auth-wind-pattern";
    windPattern.src = "res/img/pattern-wind.svg";
    windPattern.alt = "";

    // 2. Corner Brackets (Exact Top-Left and Bottom-Right on outer card)
    const cornerTL = document.createElement("span");
    cornerTL.className = "auth-bracket auth-bracket-tl";
    const cornerBR = document.createElement("span");
    cornerBR.className = "auth-bracket auth-bracket-br";

    // 3. Subtitle / Brand Header: —— VÕ LÂM HIỆP TRUYỆN - IDLE ——
    const subBrand = document.createElement("div");
    subBrand.className = "auth-sub-brand";
    subBrand.innerHTML = `<span class="auth-sub-dash">——</span> VÕ LÂM HIỆP TRUYỆN - IDLE <span class="auth-sub-dash">——</span>`;

    // 4. Input Fields Container
    const formBox = document.createElement("div");
    formBox.className = "auth-form-box";

    // Username Group
    const grpUser = document.createElement("div");
    grpUser.className = "auth-field-group";
    const boxUser = document.createElement("div");
    boxUser.className = "auth-input-box";
    boxUser.innerHTML = `<i class="fa-solid fa-user input-icon"></i>`;
    uInput.placeholder = "Tên Tài Khoản";
    boxUser.appendChild(uInput);
    grpUser.appendChild(boxUser);

    // Password Group
    const grpPass = document.createElement("div");
    grpPass.className = "auth-field-group";
    const boxPass = document.createElement("div");
    boxPass.className = "auth-input-box";
    boxPass.innerHTML = `<i class="fa-solid fa-key input-icon"></i>`;
    pInput.placeholder = "Mật Khẩu";
    boxPass.appendChild(pInput);
    grpPass.appendChild(boxPass);

    // Option Checkboxes (Remember & Show Password)
    const optRow = document.createElement("div");
    optRow.className = "auth-options-row";

    const optRem = document.createElement("div");
    optRem.className = "auth-check-item";
    if (remCb) optRem.appendChild(remCb);
    if (remLbl) {
      remLbl.innerHTML = `<i class="fa-solid fa-bookmark" style="font-size:11px;margin-right:4px;"></i>Nhớ tài khoản`;
      optRem.appendChild(remLbl);
    }

    const optShow = document.createElement("div");
    optShow.className = "auth-check-item";
    if (showCb) optShow.appendChild(showCb);
    if (showLbl) {
      showLbl.innerHTML = `<i class="fa-solid fa-eye" style="font-size:11px;margin-right:4px;"></i>Hiện mật khẩu`;
      optShow.appendChild(showLbl);
    }

    optRow.appendChild(optRem);
    optRow.appendChild(optShow);

    formBox.appendChild(grpUser);
    formBox.appendChild(grpPass);
    formBox.appendChild(optRow);

    // 5. Action Buttons (Double-Border Antique Brass style)
    btnIn.className = "auth-btn auth-btn-primary";
    btnIn.innerHTML = `<span><i class="fa-solid fa-arrow-right-to-bracket"></i> ĐĂNG NHẬP</span>`;

    btnUp.className = "auth-btn auth-btn-secondary";
    btnUp.innerHTML = `<span><i class="fa-solid fa-user-plus"></i> ĐĂNG KÝ TÀI KHOẢN</span>`;

    const actCol = document.createElement("div");
    actCol.className = "auth-actions-col";
    actCol.appendChild(btnIn);
    actCol.appendChild(btnUp);

    // 6. Content Wrapper for stacking above pattern
    const contentWrap = document.createElement("div");
    contentWrap.className = "auth-content-wrap";
    contentWrap.appendChild(subBrand);
    contentWrap.appendChild(formBox);
    contentWrap.appendChild(actCol);

    // 7. Rebuild .ng2 Container cleanly
    ng2.innerHTML = "";
    ng2.appendChild(windPattern);
    ng2.appendChild(cornerTL);
    ng2.appendChild(cornerBR);
    ng2.appendChild(contentWrap);

    // Re-check for error notice from retry/server
    if (ng2x) {
      const errEl = ng2x.querySelector(".reqbad");
      const retryBtn = ng2x.querySelector("#ngRetry");
      if (errEl || retryBtn) {
        const noticeBox = document.createElement("div");
        noticeBox.className = "auth-notice-box";
        if (errEl) noticeBox.appendChild(errEl);
        if (retryBtn) noticeBox.appendChild(retryBtn);
        formBox.prepend(noticeBox);
      }
    }

    ensureLandingFx();
    syncResolutionScale();
  }

  // Wuxia Atmospheric Particle & Mist Renderer (High-Performance 60FPS)
  window.initWuxiaAtmosphere = function (canvas, opts) {
    opts = opts || {};
    if (!canvas || !canvas.getContext) return null;
    const ctx = canvas.getContext("2d");
    if (!ctx) return null;

    let animId = null;
    let resizeRaf = null;
    let active = true;

    function resize() {
      const parent = canvas.parentElement;
      const pw = parent && parent.clientWidth > 0 ? parent.clientWidth : window.innerWidth;
      const ph = parent && parent.clientHeight > 0 ? parent.clientHeight : window.innerHeight;
      if (canvas.width !== pw || canvas.height !== ph) {
        canvas.width = pw;
        canvas.height = ph;
      }
    }
    resize();

    function onResizeThrottled() {
      if (resizeRaf) return;
      resizeRaf = requestAnimationFrame(() => {
        resizeRaf = null;
        resize();
      });
    }
    window.addEventListener("resize", onResizeThrottled, { passive: true });

    // Subtle Golden Qi Embers (Low count, fast 2-pass drawing, ZERO shadowBlur!)
    const emberCount = opts.emberCount || 20;
    const embers = [];
    for (let i = 0; i < emberCount; i++) {
      embers.push({
        x: Math.random() * (canvas.width || window.innerWidth || 1366),
        y: Math.random() * (canvas.height || window.innerHeight || 768),
        size: 1.1 + Math.random() * 1.6,
        speedY: 0.25 + Math.random() * 0.55,
        speedX: (Math.random() - 0.5) * 0.25,
        phase: Math.random() * Math.PI * 2,
        phaseSpeed: 0.02 + Math.random() * 0.025,
        alpha: 0.20 + Math.random() * 0.35,
        color: Math.random() > 0.3 ? "243, 210, 122" : "240, 170, 70"
      });
    }

    // Soft Subtle Mist Clouds (Faint, low alpha, dark wuxia mist)
    const cloudCount = opts.cloudCount !== undefined ? opts.cloudCount : 0;
    const clouds = [];
    for (let i = 0; i < cloudCount; i++) {
      clouds.push({
        x: Math.random() * (canvas.width || window.innerWidth || 1366),
        y: (canvas.height || window.innerHeight || 768) * (0.35 + Math.random() * 0.45),
        radius: 160 + Math.random() * 160,
        speedX: (0.1 + Math.random() * 0.18) * (i % 2 === 0 ? 1 : -0.8),
        speedY: (Math.random() - 0.5) * 0.06,
        alpha: 0.035 + Math.random() * 0.045,
        color: i % 2 === 0 ? "170, 135, 95" : "140, 115, 85"
      });
    }

    function render(time) {
      if (!active) return;

      const w = canvas.width;
      const h = canvas.height;
      if (w <= 0 || h <= 0) {
        resize();
        animId = requestAnimationFrame(render);
        return;
      }

      ctx.clearRect(0, 0, w, h);

      // 1. Draw subtle drifting mist clouds (only if clouds exist)
      if (clouds.length > 0) {
      for (let i = 0; i < clouds.length; i++) {
        const c = clouds[i];
        c.x += c.speedX;
        c.y += c.speedY;
        if (c.x - c.radius > w) c.x = -c.radius;
        if (c.x + c.radius < 0) c.x = w + c.radius;
        if (c.y - c.radius > h) c.y = -c.radius;
        if (c.y + c.radius < 0) c.y = h + c.radius;

        const grad = ctx.createRadialGradient(c.x, c.y, 0, c.x, c.y, c.radius);
        grad.addColorStop(0, "rgba(" + c.color + ", " + c.alpha + ")");
        grad.addColorStop(0.6, "rgba(" + c.color + ", " + (c.alpha * 0.35) + ")");
        grad.addColorStop(1, "rgba(" + c.color + ", 0)");

        ctx.fillStyle = grad;
        ctx.beginPath();
        ctx.arc(c.x, c.y, c.radius, 0, Math.PI * 2);
        ctx.fill();
      }
      }

      // 2. Draw Bagua Qi glow if enabled (for character select, soft & subtle)
      if (opts.qiAura) {
        const cx = w * 0.69;
        const cy = h * 0.52;
        const pulse = 1 + Math.sin(time * 0.0016) * 0.06;
        const qiRadius = 260 * pulse;
        const qiGrad = ctx.createRadialGradient(cx, cy, 20, cx, cy, qiRadius);
        qiGrad.addColorStop(0, "rgba(243, 210, 122, 0.12)");
        qiGrad.addColorStop(0.4, "rgba(212, 140, 50, 0.06)");
        qiGrad.addColorStop(0.8, "rgba(180, 100, 30, 0.02)");
        qiGrad.addColorStop(1, "rgba(0, 0, 0, 0)");
        ctx.fillStyle = qiGrad;
        ctx.beginPath();
        ctx.arc(cx, cy, qiRadius, 0, Math.PI * 2);
        ctx.fill();
      }

      // 3. Draw floating golden embers (High performance, ZERO shadowBlur!)
      for (let j = 0; j < embers.length; j++) {
        const e = embers[j];
        e.y -= e.speedY;
        e.phase += e.phaseSpeed;
        e.x += e.speedX + Math.sin(e.phase) * 0.35;

        if (e.y < -10) {
          e.y = h + 10;
          e.x = Math.random() * w;
        }
        if (e.x < -10) e.x = w + 10;
        if (e.x > w + 10) e.x = -10;

        const currentAlpha = Math.max(0, Math.min(1, e.alpha * (0.7 + 0.3 * Math.sin(e.phase))));

        // Outer soft glow halo (fast 2D arc, no GPU shadow blur overhead)
        ctx.fillStyle = "rgba(" + e.color + ", " + (currentAlpha * 0.18) + ")";
        ctx.beginPath();
        ctx.arc(e.x, e.y, e.size * 2.2, 0, Math.PI * 2);
        ctx.fill();

        // Inner bright spark
        ctx.fillStyle = "rgba(" + e.color + ", " + currentAlpha + ")";
        ctx.beginPath();
        ctx.arc(e.x, e.y, e.size, 0, Math.PI * 2);
        ctx.fill();
      }

      animId = requestAnimationFrame(render);
    }

    animId = requestAnimationFrame(render);

    return {
      destroy: function () {
        active = false;
        if (animId) cancelAnimationFrame(animId);
        if (resizeRaf) cancelAnimationFrame(resizeRaf);
        window.removeEventListener("resize", onResizeThrottled);
      }
    };
  };

  function ensureLandingWatermarks() {
    if (!document.body.classList.contains("ngate-on")) return;
    let identify = document.getElementById("cornerIdentify");
    if (!identify) {
      identify = document.createElement("img");
      identify.id = "cornerIdentify";
      identify.className = "landing-corner-identify";
      identify.src = "res/img/identify_.png";
      identify.alt = "18+";
    }
    if (identify.parentElement !== document.body) {
      document.body.appendChild(identify);
    }

    let logo = document.getElementById("landingLogoText");
    if (!logo) {
      logo = document.createElement("img");
      logo.id = "landingLogoText";
      logo.className = "landing-top-logo";
      logo.src = "res/img/logo_text.png";
      logo.alt = "Võ Lâm Hiệp Truyện - IDLE";
    }
    if (logo.parentElement !== document.body) {
      document.body.appendChild(logo);
    }
  }

  let landingFxInstance = null;
  function ensureLandingFx() {
    const modal = document.getElementById("modal");
    if (!modal || !document.body.classList.contains("ngate-on") || modal.classList.contains("hidden")) {
      if (landingFxInstance) {
        landingFxInstance.destroy();
        landingFxInstance = null;
      }
      return;
    }

    let fx = document.getElementById("landingAmbientFx");
    if (!fx) {
      fx = document.createElement("div");
      fx.id = "landingAmbientFx";
      fx.className = "landing-ambient-fx";
      fx.innerHTML = '<canvas class="landing-ambient-canvas" id="landingAmbientCanvas"></canvas>';
      modal.insertBefore(fx, modal.firstChild);
    }

    if (!landingFxInstance) {
      const canvas = document.getElementById("landingAmbientCanvas");
      if (canvas && typeof window.initWuxiaAtmosphere === "function") {
        landingFxInstance = window.initWuxiaAtmosphere(canvas, { emberCount: 24, cloudCount: 0 });
      }
    }
  }

  function syncResolutionScale() {
    const cnew = document.getElementById("cnew");
    if (cnew) {
      const vh = window.innerHeight;
      const vw = window.innerWidth;
      let scale = 1;
      if (vh < 690) {
        scale = Math.max(0.65, (vh - 24) / 670);
      }
      if (vw < 980) {
        const wScale = Math.max(0.65, (vw - 24) / 980);
        scale = Math.min(scale, wScale);
      }
      cnew.style.setProperty("--panel-scale", scale);
    }
  }
  window.addEventListener("resize", syncResolutionScale, { passive: true });
  window.syncResolutionScale = syncResolutionScale;

  // Observe modal mutations to automatically enhance newly rendered auth forms
  const observer = new MutationObserver(() => {
    cleanLegacyStyles();
    if (document.querySelector(".ng2")) {
      enhanceAuthModal();
    }
    ensureLandingWatermarks();
    ensureLandingFx();
    syncResolutionScale();
  });

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => {
      const modal = document.getElementById("modal") || document.body;
      observer.observe(modal, { childList: true, subtree: true });
      enhanceAuthModal();
      ensureLandingWatermarks();
      ensureLandingFx();
      syncResolutionScale();
    });
  } else {
    const modal = document.getElementById("modal") || document.body;
    observer.observe(modal, { childList: true, subtree: true });
    enhanceAuthModal();
    ensureLandingWatermarks();
    ensureLandingFx();
    syncResolutionScale();
  }

  // Global Logout Handler: guarantees clean logout straight to login screen without popup dialog
  document.addEventListener("click", async function (e) {
    const logoutBtn = e.target && e.target.closest && e.target.closest("#bLogout, #csOut, #naOut, #ncLogout");
    if (logoutBtn) {
      e.stopImmediatePropagation();
      e.preventDefault();

      try {
        if (window.B && window.B.sb && window.B.sb.auth) {
          window.B.loggingOut = true;
          await window.B.sb.auth.signOut();
        }
      } catch (err) {}

      if (window.JXSession) {
        window.JXSession.clear();
      }

      if (window.B) window.B.user = null;
      if (window.o) window.o = null;

      // Ensure active character selection / create screens are removed immediately
      const cnew = document.getElementById("cnew");
      if (cnew) cnew.remove();
      const csel = document.getElementById("csel");
      if (csel) csel.remove();

      // Show landing gate immediately
      document.body.classList.add("ngate-on");
      const modal = document.getElementById("modal");
      if (modal) {
        modal.classList.remove("hidden");
      }
      enhanceAuthModal();
      ensureLandingWatermarks();
      ensureLandingFx();

      if (typeof window.updateViewportState === "function") {
        window.updateViewportState();
      }

      window.location.href = window.location.origin + window.location.pathname;
    }
  }, true);

  // 10. Heartbeat Monitor & Force Logout Handling
  let heartbeatTimer = null;
  let offlineCounter = 0;

  function showAuthNotice(msg) {
    const formBox = document.querySelector(".auth-form-box");
    if (!formBox) return;
    let noticeBox = document.querySelector(".auth-notice-box");
    if (!noticeBox) {
      noticeBox = document.createElement("div");
      noticeBox.className = "auth-notice-box";
      formBox.prepend(noticeBox);
    }
    noticeBox.innerHTML = `<p class="reqbad"><i class="fa-solid fa-triangle-exclamation"></i> ${msg}</p>`;
  }

  function forceLogoutToLogin(reason) {
    if (heartbeatTimer) {
      clearInterval(heartbeatTimer);
      heartbeatTimer = null;
    }

    if (window.JXSession) {
      window.JXSession.clear();
    }

    if (window.B) {
      window.B.user = null;
    }
    if (window.o) {
      window.o = null;
    }

    const cnew = document.getElementById("cnew");
    if (cnew) cnew.remove();
    const csel = document.getElementById("csel");
    if (csel) csel.remove();

    // Force display login gate overlay
    document.body.classList.add("ngate-on");
    window.NET_GATE = true;
    const modal = document.getElementById("modal");
    if (modal) {
      modal.classList.remove("hidden");
    }

    if (typeof window.updateViewportState === "function") {
      window.updateViewportState();
    }

    enhanceAuthModal();
    if (reason) {
      setTimeout(() => showAuthNotice(reason), 100);
    }
  }

  window.forceLogoutToLogin = forceLogoutToLogin;

  function startHeartbeatMonitor() {
    if (heartbeatTimer) clearInterval(heartbeatTimer);

    heartbeatTimer = setInterval(async () => {
      const user = window.JXSession ? window.JXSession.getUser() : null;
      const token = window.JXSession ? window.JXSession.getToken() : null;
      const sid = window.JXSession ? window.JXSession.getSid() : null;

      // Only check when user is logged in and not already on gate screen
      if (!user || !token || document.body.classList.contains("ngate-on")) {
        return;
      }

      try {
        const res = await fetch("/api/heartbeat", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${token}`
          },
          body: JSON.stringify({ username: user, sessionId: sid })
        });

        if (!res.ok && (res.status === 401 || res.status === 403)) {
          const errData = await res.json().catch(() => ({}));
          forceLogoutToLogin(errData.reason || "Tài khoản bị từ chối truy cập (FORBID)");
          return;
        }

        const data = await res.json().catch(() => ({}));
        if (data && data.kick) {
          forceLogoutToLogin(data.reason || "Phiên đăng nhập đã kết thúc");
          return;
        }

        offlineCounter = 0;
      } catch (err) {
        offlineCounter++;
        if (offlineCounter >= 2) {
          forceLogoutToLogin("Mất kết nối máy chủ hoặc máy chủ đang bảo trì");
        }
      }
    }, 10000);
  }

  startHeartbeatMonitor();
})();
